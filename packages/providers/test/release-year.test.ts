import { describe, expect, it } from "vitest";
import { MusicBrainzReleaseYears, YouTubeAdapter, parseVideoTitle, releaseYearFromDescription } from "../src";
import { stubFetch, youtubeVideo } from "./fixtures";

describe("release years for YouTube picks", () => {
  it("never uses the upload date as the release year", async () => {
    const { fetch } = stubFetch({ "/videos": { items: [youtubeVideo({ id: "bump", title: "R. Kelly - Bump n' Grind (Official Video)", channel: "RKellyVEVO" })] } });
    const yt = new YouTubeAdapter({ apiKey: "k", fetch });
    const [video] = await yt.getVideos(["bump"]);
    // The fixture was uploaded in 2009; that must not become the song's year.
    expect(video!.releaseYear).toBeUndefined();
  });

  it("reads the release date official uploads put in the description", async () => {
    const description = "Provided to YouTube by RCA Records Label\n\nBump n' Grind · R. Kelly\n\n12 Play\n\n℗ 1993 Zomba Recording LLC\n\nReleased on: 1993-11-09\n\nAuto-generated by YouTube.";
    expect(releaseYearFromDescription(description)).toBe(1993);
    expect(releaseYearFromDescription("℗ 2011 Remaster ℗ 1994 Original")).toBe(1994);
    expect(releaseYearFromDescription("Subscribe for more! Uploaded 2009")).toBeUndefined();
    expect(releaseYearFromDescription(undefined)).toBeUndefined();

    const v = youtubeVideo({ id: "topic", title: "Bump n' Grind", channel: "R. Kelly - Topic" });
    const { fetch } = stubFetch({ "/videos": { items: [{ ...v, snippet: { ...v.snippet, description } }] } });
    const [video] = await new YouTubeAdapter({ apiKey: "k", fetch }).getVideos(["topic"]);
    expect(video!.releaseYear).toBe(1993);
  });

  it("splits a video title into artist and song", () => {
    expect(parseVideoTitle({ title: "R. Kelly - Bump n' Grind (Official Video)", artistName: "RKelly" })).toEqual({ artist: "R. Kelly", title: "Bump n' Grind" });
    expect(parseVideoTitle({ title: "Bump n' Grind", artistName: "R. Kelly" })).toEqual({ artist: "R. Kelly", title: "Bump n' Grind" });
    expect(parseVideoTitle({ title: 'Usher - "U Remind Me" (feat. Nobody) [HD] | Arista', artistName: "UsherVEVO" })).toEqual({ artist: "Usher", title: "U Remind Me" });
  });
});

describe("MusicBrainz release years", () => {
  const recording = (title: string, artist: string, date: string | undefined, score = 100) => ({
    score,
    title,
    ...(date ? { "first-release-date": date } : {}),
    "artist-credit": [{ name: artist }],
  });

  it("returns the earliest release among matching recordings, skipping compilations' later dates and other artists", async () => {
    const { fetch, calls } = stubFetch({
      "/ws/2/recording": {
        recordings: [
          recording("Bump n' Grind (remix)", "R. Kelly", "1994-03-01", 90),
          recording("Bump n’ Grind", "R. Kelly", "2009-06-01"),
          recording("Bump n' Grind", "R. Kelly", "1993-11-09"),
          recording("Bump n' Grind", "Someone Else", "1985-01-01"),
          recording("Something Else", "R. Kelly", "1990-01-01"),
          recording("Bump n' Grind", "R. Kelly", undefined),
        ],
      },
    });
    const mb = new MusicBrainzReleaseYears({ userAgent: "VYBZ-test/1.0 (test)", fetch, intervalMs: 0 });
    expect(await mb.firstReleaseYear("R. Kelly", "Bump n' Grind")).toBe(1993);
    expect((calls[0]!.init?.headers as Record<string, string>)["User-Agent"]).toBe("VYBZ-test/1.0 (test)");
    expect(calls[0]!.url.searchParams.get("query")).toBe('recording:"Bump n\' Grind" AND artist:"R. Kelly"');
  });

  it("returns null when nothing matches or the service fails", async () => {
    const empty = stubFetch({ "/ws/2/recording": { recordings: [] } });
    expect(await new MusicBrainzReleaseYears({ userAgent: "t", fetch: empty.fetch, intervalMs: 0 }).firstReleaseYear("A", "B")).toBeNull();
    const down = stubFetch({ "/ws/2/recording": {} }, 503);
    expect(await new MusicBrainzReleaseYears({ userAgent: "t", fetch: down.fetch, intervalMs: 0 }).firstReleaseYear("A", "B")).toBeNull();
  });

  it("spaces requests out", async () => {
    const { fetch, calls } = stubFetch({ "/ws/2/recording": { recordings: [] } });
    const mb = new MusicBrainzReleaseYears({ userAgent: "t", fetch, intervalMs: 50 });
    const t0 = Date.now();
    await Promise.all([mb.firstReleaseYear("A", "B"), mb.firstReleaseYear("C", "D")]);
    expect(calls).toHaveLength(2);
    expect(Date.now() - t0).toBeGreaterThanOrEqual(45);
  });
});
